//! The binary-repo half of a release: write the version, note the candidate
//! in the changelog, commit, tag, push.
//!
//! This mirrors `bump_version.sh rc|promote`: `VERSION` plus its mirrors, an
//! rc marker under `## [Unreleased]`, one commit and one annotated tag. The
//! tag message names the tool that produced it, so `git tag -n` explains the
//! commit without a changelog lookup.

use std::path::Path;

use crate::runner::Runner;

use super::model::WorkflowConfig;
use super::util::{git_repo_clean, run_git, write_version_to_file};

/// Writes the new version to the version file and its mirrors, inserts the rc
/// changelog marker, then commits and tags.
pub fn bump_and_tag(
    runner: &Runner,
    cfg: &WorkflowConfig,
    current: &str,
    next: &str,
    bump_type: &str,
) -> Result<(), String> {
    // Safety: the tree must be clean for tracked files (mirror files may be
    // untracked-but-pending, so the check ignores untracked files).
    git_repo_clean(runner)?;

    let version_file = cfg.binary_repo.version_file.clone();
    let mut files_to_add = vec![version_file.clone()];
    let changelog_rel = cfg.binary_repo.changelog_file.clone();
    let (rel, changed) = update_rc_changelog(&runner.dir, &changelog_rel, next, bump_type)?;
    if changed {
        files_to_add.push(rel);
    }

    write_version_to_file(&runner.dir, &version_file, next)
        .map_err(|error| format!("write {version_file}: {error}"))?;
    for mirror in &cfg.binary_repo.mirror_files {
        if mirror.is_empty() || *mirror == version_file {
            continue;
        }
        write_version_to_file(&runner.dir, mirror, next)
            .map_err(|error| format!("write mirror {mirror}: {error}"))?;
        files_to_add.push(mirror.clone());
    }

    let mut add_args: Vec<&str> = vec!["add"];
    add_args.extend(files_to_add.iter().map(String::as_str));
    run_git(runner, &add_args)
        .map_err(|error| format!("git add {}: {error}", files_to_add.join(" ")))?;

    let msg = if bump_type == "promote" {
        format!("promote: {current} → {next}")
    } else {
        format!("bump: version {current} → {next}")
    };
    run_git(runner, &["commit", "-m", &msg]).map_err(|error| format!("git commit: {error}"))?;

    let tag = format!("v{next}");
    let tag_msg = format!(
        "{} {next}\n\n{msg}\nGenerated by devine-utils-ci workflow.",
        cfg.binary_repo.name
    );
    run_git(runner, &["tag", "-a", &tag, "-m", &tag_msg])
        .map_err(|error| format!("git tag -a {tag}: {error}"))?;
    println!("  ✓ committed {msg:?} and created tag {tag}");
    Ok(())
}

/// Inserts the release-candidate marker under `## [Unreleased]`.
///
/// Returns the changelog path and whether it changed. A declared changelog
/// that cannot be read, or one without the heading, fails closed: otherwise
/// the tag pipeline would reject the version/changelog drift after the push.
/// When no changelog is declared, a missing `CHANGELOG.md` is simply skipped.
pub fn update_rc_changelog(
    dir: &Path,
    rel: &str,
    next: &str,
    bump_type: &str,
) -> Result<(String, bool), String> {
    if bump_type != "rc" {
        return Ok((String::new(), false));
    }
    let explicit = !rel.is_empty();
    let rel = if rel.is_empty() { "CHANGELOG.md" } else { rel };
    let path = dir.join(rel);
    let data = match std::fs::read_to_string(&path) {
        Ok(data) => data,
        Err(error) if !explicit && error.kind() == std::io::ErrorKind::NotFound => {
            return Ok((String::new(), false))
        }
        Err(error) => return Err(format!("read changelog {rel}: {error}")),
    };
    let heading = "## [Unreleased]";
    let Some(index) = data.find(heading) else {
        return Err(format!("changelog {rel} has no {heading:?} section"));
    };
    let (insert_at, prefix) = match data[index..].find('\n') {
        Some(offset) => (index + offset + 1, "\n"),
        None => (data.len(), "\n\n"),
    };
    let rc = match next.rfind("-rc.") {
        Some(at) => format!("rc.{}", &next[at + 4..]),
        None => next.to_string(),
    };
    let today = chrono::Local::now().format("%Y-%m-%d");
    let note =
        format!("- **{rc}（{today}）**：发布候选版本；构建、UAT 产物与下游验证见正式版变更记录。");
    let mut updated = String::with_capacity(data.len() + note.len() + 8);
    updated.push_str(&data[..insert_at]);
    updated.push_str(prefix);
    updated.push_str(&note);
    updated.push('\n');
    updated.push_str(&data[insert_at..]);
    std::fs::write(&path, updated).map_err(|error| format!("write changelog {rel}: {error}"))?;
    Ok((rel.to_string(), true))
}

/// Pushes the current branch, then the tag, to the binary repo's remote.
pub fn push_main_and_tag(runner: &Runner, cfg: &WorkflowConfig, tag: &str) -> Result<(), String> {
    let remote = if cfg.binary_repo.remote.is_empty() {
        "origin"
    } else {
        cfg.binary_repo.remote.as_str()
    };
    run_git(runner, &["push", remote, "HEAD"])
        .map_err(|error| format!("git push {remote} HEAD: {error}"))?;
    println!("  ✓ pushed main to {remote}");
    run_git(runner, &["push", remote, tag])
        .map_err(|error| format!("git push {remote} {tag}: {error}"))?;
    println!("  ✓ pushed tag {tag} to {remote}");
    Ok(())
}

